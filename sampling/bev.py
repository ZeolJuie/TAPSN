def load_pedestrian_trajectories(csv_path):
    trajectories = {}
    with csv_path.open(encoding="utf-8") as handle:
        reader = csv.DictReader(handle)
        for row in reader:
            ped_id = row["ped_id"]
            point = {
                "frame": int(row["frame"]),
                "time": float(row["time"]),
                "x": float(row["x"]),
                "y": float(row["y"]),
                "mode": row["mode"],
                "group_id": int(row.get("group_id", -1)),
                "group_member_index": int(row.get("group_member_index", 0)),
            }
            trajectories.setdefault(ped_id, []).append(point)

    for ped_id in trajectories:
        trajectories[ped_id].sort(key=lambda point: (point["frame"], point["time"]))

    return trajectories


def load_vehicle_trajectories(csv_path):
    if csv_path is None or not csv_path.exists():
        return {}

    trajectories = {}
    with csv_path.open(encoding="utf-8") as handle:
        reader = csv.DictReader(handle)
        for row in reader:
            veh_id = row["veh_id"]
            point = {
                "frame": int(row["frame"]),
                "time": float(row["time"]),
                "x": float(row["x"]),
                "y": float(row["y"]),
                "heading": float(row["heading"]),
                "vel": float(row["vel"]),
            }
            trajectories.setdefault(veh_id, []).append(point)

    for veh_id in trajectories:
        trajectories[veh_id].sort(key=lambda point: (point["frame"], point["time"]))
    return trajectories


def hex_to_rgb(color):
    color = color.lstrip("#")
    return tuple(int(color[index:index + 2], 16) / 255.0 for index in (0, 2, 4))


def rgb_to_hex(rgb):
    channels = [max(0, min(255, int(round(channel * 255.0)))) for channel in rgb]
    return "#{:02X}{:02X}{:02X}".format(*channels)


def adjust_color_variant(color, member_index):
    red, green, blue = hex_to_rgb(color)
    hue, lightness, saturation = colorsys.rgb_to_hls(red, green, blue)
    variant_offsets = (-0.08, 0.0, 0.09, -0.14, 0.15)
    lightness = max(0.22, min(0.82, lightness + variant_offsets[member_index % len(variant_offsets)]))
    saturation = max(0.35, min(0.95, saturation + 0.04))
    return rgb_to_hex(colorsys.hls_to_rgb(hue, lightness, saturation))


def trajectory_color_map(trajectories):
    group_members = {}
    for ped_id, samples in trajectories.items():
        first = samples[0]
        group_id = int(first.get("group_id", -1))
        if group_id >= 0:
            group_members.setdefault(group_id, []).append((int(first.get("group_member_index", 0)), ped_id))

    color_map = {}
    ungrouped_ids = []
    for ped_id, samples in trajectories.items():
        first = samples[0]
        group_id = int(first.get("group_id", -1))
        member_index = int(first.get("group_member_index", 0))
        if group_id < 0:
            ungrouped_ids.append(ped_id)
            continue
        base_color = PALETTE[group_id % len(PALETTE)]
        color_map[ped_id] = adjust_color_variant(base_color, member_index)

    for index, ped_id in enumerate(sorted(ungrouped_ids, key=lambda value: int(value) if value.isdigit() else value)):
        color_map[ped_id] = PALETTE[index % len(PALETTE)]

    return color_map


def load_border_polylines(csv_path, step=1, break_distance=1.0):
    if csv_path is None or not csv_path.exists():
        return []

    points = []
    with csv_path.open(encoding="utf-8") as handle:
        reader = csv.DictReader(handle)
        for index, row in enumerate(reader):
            if step > 1 and index % step != 0:
                continue
            points.append((float(row["x"]), float(row["y"])))

    polylines = []
    current = []
    previous = None
    for point in points:
        if previous is not None and math.hypot(point[0] - previous[0], point[1] - previous[1]) > break_distance:
            if len(current) >= 2:
                polylines.append(current)
            current = []
        current.append(point)
        previous = point

    if len(current) >= 2:
        polylines.append(current)
    return polylines


def load_obstacle_polygons(csv_path):
    if csv_path is None or not csv_path.exists():
        return []

    grouped = {}
    with csv_path.open(encoding="utf-8") as handle:
        reader = csv.DictReader(handle)
        for row in reader:
            obs_id = row["obs_id"]
            if obs_id not in grouped:
                grouped[obs_id] = {
                    "obs_id": int(obs_id),
                    "center": (float(row["obs_pos_x"]), float(row["obs_pos_y"])),
                    "points": [],
                }
            grouped[obs_id]["points"].append((float(row["x"]), float(row["y"])))
    return list(grouped.values())


def load_scene_cell(catalog_path, scene_id):
    if catalog_path is None or scene_id is None:
        return None

    catalog = json.loads(catalog_path.read_text(encoding="utf-8"))
    try:
        cell = next(cell for cell in catalog["cells"] if cell["id"] == scene_id)
    except StopIteration as exc:
        raise ValueError(f"Scene {scene_id!r} not found in {catalog_path}.") from exc
    return cell


def load_scene_subgraph(catalog_path, scene_id):
    cell = load_scene_cell(catalog_path, scene_id)
    if cell is None:
        return []

    polylines = []
    for edge in cell.get("edges", []):
        points = edge.get("points", [])
        if len(points) >= 2:
            polylines.append([(float(x), float(y)) for x, y in points])
    return polylines


def resolve_scene_subgraph_args(args):
    catalog_path = REPO_ROOT / args.catalog_path if args.catalog_path is not None else None
    scene_id = args.scene_id

    if args.scenario_config is not None:
        config = tomllib.load(args.scenario_config.open("rb"))
        map_config = config.get("map", {})
        scene_id = scene_id or map_config.get("scene_id")
        if catalog_path is None:
            map_name = map_config.get("map_name")
            configured_catalog = map_config.get("scene_catalog_path")
            if configured_catalog is not None:
                catalog_path = REPO_ROOT / Path(configured_catalog)
            elif map_name is not None:
                catalog_path = REPO_ROOT / "topology" / str(map_name) / "walkable_cells.json"

    return catalog_path, scene_id


def trajectory_extent(trajectories, margin=0.0):
    xs = []
    ys = []

    for samples in trajectories.values():
        xs.extend(point["x"] for point in samples)
        ys.extend(point["y"] for point in samples)

    if not xs or not ys:
        raise ValueError("No pedestrian trajectory points found to render.")

    return {
        "min_x": min(xs) - margin,
        "max_x": max(xs) + margin,
        "min_y": min(ys) - margin,
        "max_y": max(ys) + margin,
    }


def crop_border_points(border_points, focus_extent):
    if not border_points:
        return []

    cropped = []
    for x, y in border_points:
        if focus_extent["min_x"] <= x <= focus_extent["max_x"] and focus_extent["min_y"] <= y <= focus_extent["max_y"]:
            cropped.append((x, y))
    return cropped


def extent_from_scene_bounds(bounds, padding=1.0):
    return {
        "min_x": float(bounds["min_x"]) - padding,
        "max_x": float(bounds["max_x"]) + padding,
        "min_y": float(bounds["min_y"]) - padding,
        "max_y": float(bounds["max_y"]) + padding,
    }


def bbox_for_points(points):
    xs = [point[0] for point in points]
    ys = [point[1] for point in points]
    return {
        "min_x": min(xs),
        "max_x": max(xs),
        "min_y": min(ys),
        "max_y": max(ys),
    }


def bbox_intersects(bounds_a, bounds_b):
    return not (
        bounds_a["max_x"] < bounds_b["min_x"]
        or bounds_a["min_x"] > bounds_b["max_x"]
        or bounds_a["max_y"] < bounds_b["min_y"]
        or bounds_a["min_y"] > bounds_b["max_y"]
    )


def select_polylines_in_bounds(polylines, bounds):
    selected = []
    for polyline in polylines:
        if len(polyline) < 2:
            continue
        if bbox_intersects(bbox_for_points(polyline), bounds):
            selected.append(polyline)
    return selected


def select_obstacles_in_bounds(obstacles, bounds):
    selected = []
    for obstacle in obstacles:
        points = obstacle.get("points", [])
        if len(points) < 3:
            continue
        if bbox_intersects(bbox_for_points(points), bounds):
            selected.append(obstacle)
    return selected


def gather_extent(trajectories, border_polylines, topology_polylines, vehicle_trajectories=None, scene_bounds=None):
    if scene_bounds is not None:
        return extent_from_scene_bounds(scene_bounds, padding=1.0)

    xs = []
    ys = []

    for samples in trajectories.values():
        xs.extend(point["x"] for point in samples)
        ys.extend(point["y"] for point in samples)

    for samples in (vehicle_trajectories or {}).values():
        xs.extend(point["x"] for point in samples)
        ys.extend(point["y"] for point in samples)

    for polyline in border_polylines:
        xs.extend(point[0] for point in polyline)
        ys.extend(point[1] for point in polyline)

    for polyline in topology_polylines:
        xs.extend(point[0] for point in polyline)
        ys.extend(point[1] for point in polyline)

    if not xs or not ys:
        raise ValueError("No trajectory or border points found to render.")

    min_x = min(xs)
    max_x = max(xs)
    min_y = min(ys)
    max_y = max(ys)

    span_x = max(max_x - min_x, 1.0)
    span_y = max(max_y - min_y, 1.0)
    padding_x = span_x * 0.08
    padding_y = span_y * 0.08

    return {
        "min_x": min_x - padding_x,
        "max_x": max_x + padding_x,
        "min_y": min_y - padding_y,
        "max_y": max_y + padding_y,
    }


def make_projection(extent, width, height, margin=72, title_height=56):
    plot_left = margin
    plot_top = margin + title_height
    plot_width = width - margin * 2
    plot_height = height - plot_top - margin

    world_width = extent["max_x"] - extent["min_x"]
    world_height = extent["max_y"] - extent["min_y"]
    scale = min(plot_width / world_width, plot_height / world_height)

    used_width = world_width * scale
    used_height = world_height * scale
    offset_x = plot_left + (plot_width - used_width) * 0.5
    offset_y = plot_top + (plot_height - used_height) * 0.5

    def project(point):
        x, y = point
        canvas_x = offset_x + (x - extent["min_x"]) * scale
        canvas_y = offset_y + used_height - (y - extent["min_y"]) * scale
        return canvas_x, canvas_y

    return {
        "plot_left": plot_left,
        "plot_top": plot_top,
        "plot_width": plot_width,
        "plot_height": plot_height,
        "used_width": used_width,
        "used_height": used_height,
        "offset_x": offset_x,
        "offset_y": offset_y,
        "scale": scale,
        "project": project,
    }


def polyline_path(points):
    return " ".join(f"{x:.2f},{y:.2f}" for x, y in points)


def escape(text):
    return html.escape(str(text), quote=True)


def arrowhead_points(points, arrow_length=12.0, arrow_width=8.0):
    if len(points) < 2:
        return None

    end_x, end_y = points[-1]
    start_x, start_y = points[-2]
    dx = end_x - start_x
    dy = end_y - start_y
    norm = math.hypot(dx, dy)
    if norm <= 1e-6:
        return None

    ux = dx / norm
    uy = dy / norm
    px = -uy
    py = ux

    tip = (end_x, end_y)
    base = (end_x - ux * arrow_length, end_y - uy * arrow_length)
    left = (base[0] + px * arrow_width * 0.5, base[1] + py * arrow_width * 0.5)
    right = (base[0] - px * arrow_width * 0.5, base[1] - py * arrow_width * 0.5)
    return [tip, left, right]


def midpoint_arrowhead_points(points, arrow_length=14.0, arrow_width=9.0):
    if len(points) < 2:
        return None

    cumulative = [0.0]
    for start, end in zip(points, points[1:]):
        cumulative.append(cumulative[-1] + math.hypot(end[0] - start[0], end[1] - start[1]))

    total_length = cumulative[-1]
    if total_length <= 1e-6:
        return None

    target = total_length * 0.5
    for index in range(1, len(points)):
        segment_length = cumulative[index] - cumulative[index - 1]
        if segment_length <= 1e-6:
            continue
        if cumulative[index] >= target:
            start_x, start_y = points[index - 1]
            end_x, end_y = points[index]
            ratio = (target - cumulative[index - 1]) / segment_length
            mid_x = start_x + (end_x - start_x) * ratio
            mid_y = start_y + (end_y - start_y) * ratio
            dx = end_x - start_x
            dy = end_y - start_y
            norm = math.hypot(dx, dy)
            if norm <= 1e-6:
                return None
            ux = dx / norm
            uy = dy / norm
            px = -uy
            py = ux
            tip = (mid_x + ux * arrow_length * 0.55, mid_y + uy * arrow_length * 0.55)
            base = (mid_x - ux * arrow_length * 0.45, mid_y - uy * arrow_length * 0.45)
            left = (base[0] + px * arrow_width * 0.5, base[1] + py * arrow_width * 0.5)
            right = (base[0] - px * arrow_width * 0.5, base[1] - py * arrow_width * 0.5)
            return [tip, left, right]
    return None


def nice_scale_length(world_span):
    target = max(world_span * 0.18, 1.0)
    exponent = math.floor(math.log10(target))
    base = 10 ** exponent
    for candidate in (1, 2, 5, 10):
        length = candidate * base
        if length >= target:
            return length
    return 10 * base


def parse_ego_ped_id(ego_selection_path):
    if ego_selection_path is None or not ego_selection_path.exists():
        return None

    payload = json.loads(ego_selection_path.read_text(encoding="utf-8"))
    resolved = payload.get("resolved_ego") or {}
    ped_name = resolved.get("ped_name")
    if not ped_name:
        return None
    if isinstance(ped_name, str) and ped_name.startswith("ped_"):
        return ped_name.split("_", 1)[1]
    return str(ped_name)


def render_svg(
    trajectories,
    vehicle_trajectories,
    border_polylines,
    obstacle_polygons,
    scene_cell,
    ego_ped_id,
    width,
    height,
    title,
):
    scene_bounds = scene_cell.get("bounds") if scene_cell else None
    topology_polylines = load_scene_subgraph_from_cell(scene_cell)
    extent = gather_extent(
        trajectories,
        border_polylines,
        topology_polylines,
        vehicle_trajectories=vehicle_trajectories,
        scene_bounds=scene_bounds,
    )
    projection = make_projection(extent, width, height, margin=40, title_height=54)
    project = projection["project"]
    color_map = trajectory_color_map(trajectories)
    clipped_bounds = extent
    border_polylines = select_polylines_in_bounds(border_polylines, clipped_bounds)
    obstacle_polygons = select_obstacles_in_bounds(obstacle_polygons, clipped_bounds)

    lines = [
        f'<svg xmlns="http://www.w3.org/2000/svg" width="{width}" height="{height}" viewBox="0 0 {width} {height}" role="img">',
        f'<rect x="0" y="0" width="{width}" height="{height}" fill="{BACKGROUND}"/>',
        f'<text x="{projection["plot_left"]}" y="44" font-family="Helvetica, Arial, sans-serif" font-size="24" font-weight="700" fill="{TEXT_PRIMARY}">{escape(title)}</text>',
        f'<text x="{projection["plot_left"]}" y="68" font-family="Helvetica, Arial, sans-serif" font-size="12" fill="{TEXT_SECONDARY}">Scene-bounded BEV with local borders, obstacles, pedestrian routes, and background vehicle flow</text>',
        (
            f'<rect x="{projection["plot_left"]:.2f}" y="{projection["plot_top"]:.2f}" '
            f'width="{projection["plot_width"]:.2f}" height="{projection["plot_height"]:.2f}" '
            f'rx="20" fill="{PLOT_BACKGROUND}" stroke="{PLOT_BORDER}" stroke-width="1.5"/>'
        ),
        "<defs>",
        (
            f'<clipPath id="plot-clip"><rect x="{projection["offset_x"]:.2f}" y="{projection["offset_y"]:.2f}" '
            f'width="{projection["used_width"]:.2f}" height="{projection["used_height"]:.2f}" rx="18"/></clipPath>'
        ),
        "</defs>",
    ]

    if scene_bounds is not None:
        x1, y2 = project((scene_bounds["min_x"], scene_bounds["max_y"]))
        x2, y1 = project((scene_bounds["max_x"], scene_bounds["min_y"]))
        lines.append(
            f'<rect x="{x1:.2f}" y="{y2:.2f}" width="{x2 - x1:.2f}" height="{y1 - y2:.2f}" '
            f'fill="none" stroke="#C2C9D3" stroke-width="1.4" stroke-dasharray="5 4"/>'
        )

    lines.append('<g clip-path="url(#plot-clip)">')

    if scene_cell:
        lines.append('<g fill="none" stroke-linecap="round" stroke-linejoin="round">')
        for edge in scene_cell.get("edges", []):
            points = edge.get("points", [])
            if len(points) < 2:
                continue
            projected = [project((float(x), float(y))) for x, y in points]
            style = SCENE_EDGE_STYLE.get(edge.get("type"), {"stroke": TOPOLOGY_LINE, "width": 6.0, "opacity": 0.8})
            lines.append(
                f'<polyline points="{polyline_path(projected)}" stroke="{style["stroke"]}" stroke-width="{style["width"]:.2f}" opacity="{style["opacity"]:.2f}"/>'
            )
        lines.append("</g>")

    if border_polylines:
        lines.append('<g fill="none" stroke-linecap="round" stroke-linejoin="round">')
        for polyline in border_polylines:
            projected = [project(point) for point in polyline]
            lines.append(
                f'<polyline points="{polyline_path(projected)}" stroke="{BOUNDARY_LINE}" stroke-width="1.9" opacity="{BOUNDARY_LINE_OPACITY:.2f}"/>'
            )
        lines.append("</g>")

    if obstacle_polygons:
        lines.append('<g stroke-linejoin="round">')
        for obstacle in obstacle_polygons:
            projected = [project(point) for point in obstacle["points"]]
            lines.append(
                f'<polygon points="{polyline_path(projected)}" fill="{OBSTACLE_FILL}" stroke="{OBSTACLE_STROKE}" '
                f'stroke-width="1.0" opacity="{OBSTACLE_FILL_OPACITY:.2f}"/>'
            )
            cx, cy = project(obstacle["center"])
            lines.append(
                f'<circle cx="{cx:.2f}" cy="{cy:.2f}" r="2.4" fill="{OBSTACLE_STROKE}" opacity="0.65"/>'
            )
        lines.append("</g>")

    if vehicle_trajectories:
        lines.append('<g fill="none" stroke-linecap="round" stroke-linejoin="round">')
        for veh_id in sorted(vehicle_trajectories, key=lambda value: int(value) if str(value).isdigit() else str(value)):
            samples = vehicle_trajectories[veh_id]
            if not bbox_intersects(
                bbox_for_points([(sample["x"], sample["y"]) for sample in samples]),
                clipped_bounds,
            ):
                continue
            points = [project((sample["x"], sample["y"])) for sample in samples]
            if len(points) < 2:
                continue
            lines.append(
                f'<polyline points="{polyline_path(points)}" stroke="{VEHICLE_ROUTE}" stroke-width="2.4" opacity="{VEHICLE_ROUTE_OPACITY:.2f}"/>'
            )
        lines.append("</g>")

    ped_ids = sorted(trajectories, key=lambda value: int(value) if value.isdigit() else value)
    lines.append('<g fill="none" stroke-linecap="round" stroke-linejoin="round">')
    for ped_id in ped_ids:
        is_ego = ego_ped_id is not None and str(ped_id) == str(ego_ped_id)
        color = EGO_ROUTE if is_ego else color_map[ped_id]
        points = [project((sample["x"], sample["y"])) for sample in trajectories[ped_id]]
        if len(points) < 2:
            continue
        lines.append(
            f'<polyline points="{polyline_path(points)}" stroke="{color}" '
            f'stroke-width="{5.4 if is_ego else 3.4:.2f}" opacity="{0.98 if is_ego else NON_EGO_ROUTE_OPACITY:.2f}"/>'
        )

        arrow = midpoint_arrowhead_points(points, arrow_length=15.0 if is_ego else 13.0, arrow_width=9.0 if is_ego else 8.0)
        if arrow is not None:
            lines.append(
                f'<polygon points="{polyline_path(arrow)}" fill="{color}" opacity="{0.98 if is_ego else 0.72:.2f}"/>'
            )
    lines.append("</g>")
    lines.append("</g>")

    plot_bottom = projection["plot_top"] + projection["plot_height"]
    scale_length_world = nice_scale_length(extent["max_x"] - extent["min_x"])
    scale_length_px = scale_length_world * projection["scale"]
    scale_x = projection["plot_left"] + 24
    scale_y = plot_bottom - 26
    lines.append(
        f'<line x1="{scale_x:.2f}" y1="{scale_y:.2f}" x2="{scale_x + scale_length_px:.2f}" y2="{scale_y:.2f}" '
        f'stroke="{TEXT_PRIMARY}" stroke-width="3"/>'
    )
    lines.append(
        f'<line x1="{scale_x:.2f}" y1="{scale_y - 6:.2f}" x2="{scale_x:.2f}" y2="{scale_y + 6:.2f}" stroke="{TEXT_PRIMARY}" stroke-width="2"/>'
    )
    lines.append(
        f'<line x1="{scale_x + scale_length_px:.2f}" y1="{scale_y - 6:.2f}" x2="{scale_x + scale_length_px:.2f}" y2="{scale_y + 6:.2f}" stroke="{TEXT_PRIMARY}" stroke-width="2"/>'
    )
    lines.append(
        f'<text x="{scale_x + scale_length_px * 0.5:.2f}" y="{scale_y - 10:.2f}" text-anchor="middle" '
        f'font-family="Helvetica, Arial, sans-serif" font-size="12" fill="{TEXT_SECONDARY}">{scale_length_world:g} m</text>'
    )

    lines.append("</svg>")
    return "\n".join(lines)


def load_scene_subgraph_from_cell(scene_cell):
    if scene_cell is None:
        return []
    polylines = []
    for edge in scene_cell.get("edges", []):
        points = edge.get("points", [])
        if len(points) >= 2:
            polylines.append([(float(x), float(y)) for x, y in points])
    return polylines


